//! The check that every git hook `prek.toml` declares is installed in this clone.
//!
//! `prek.toml`'s `default_install_hook_types` changes what the next `prek install` writes, and
//! nothing reinstalls hooks on its own, so a clone can keep running its old hooks while the ones
//! added since never run. `just check` runs this first so that gap fails where someone is looking.
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

use anyhow::{bail, Context, Result};

/// What prek writes into every hook it installs.
const PREK_MARKER: &str = "File generated by prek";

/// A git hook type, such as `pre-commit`, as it names a file in the hooks directory.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct HookType(String);

impl HookType {
    /// The hook type `name` names.
    ///
    /// # Errors
    /// When `name` is empty or is not a single file name, since it is joined to the hooks
    /// directory.
    fn parse(name: &str) -> Result<Self> {
        if name.is_empty() || name.contains('/') || name == "." || name == ".." {
            bail!("{name:?} is not a git hook name");
        }
        Ok(Self(name.to_string()))
    }
}

impl std::fmt::Display for HookType {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

/// The hook types `prek.toml` tells `prek install` to write.
#[derive(Debug, PartialEq, Eq)]
pub(crate) struct DeclaredHooks(Vec<HookType>);

impl DeclaredHooks {
    /// The hook types the text of `prek.toml` declares: `default_install_hook_types`, or only
    /// `pre-commit` when it sets none, as prek does.
    ///
    /// # Errors
    /// When the text is not TOML, the key is not a list of strings, or a name in it is not a
    /// single file name.
    fn parse(prek_toml: &str) -> Result<Self> {
        let config: toml::Table = prek_toml.parse().context("not valid TOML")?;
        let Some(declared) = config.get("default_install_hook_types") else {
            return Ok(Self(vec![HookType("pre-commit".to_string())]));
        };
        let names = declared
            .as_array()
            .context("default_install_hook_types is not a list")?;
        let hooks = names
            .iter()
            .map(|name| {
                name.as_str()
                    .context("default_install_hook_types holds something other than a name")
                    .and_then(HookType::parse)
            })
            .collect::<Result<_>>()?;
        Ok(Self(hooks))
    }
}

/// Why a declared hook would not run prek's hooks.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum NotInstalled {
    /// No file is there.
    Missing,
    /// A file is there that git will not run.
    NotExecutable,
    /// An executable is there that prek did not write.
    NotPrek,
}

/// A declared hook type that is not installed, and why.
#[derive(Debug, PartialEq, Eq)]
pub(crate) struct UninstalledHook {
    hook: HookType,
    because: NotInstalled,
}

/// The directory git runs this clone's hooks from.
#[derive(Debug)]
pub(crate) struct HooksDir(PathBuf);

impl HooksDir {
    /// Where git runs hooks from for the repository at `repo`, following worktrees and
    /// `core.hooksPath`.
    ///
    /// # Errors
    /// When git cannot say, such as outside a repository.
    fn of(repo: &Path) -> Result<Self> {
        let output = Command::new("git")
            .args(["rev-parse", "--path-format=absolute", "--git-path", "hooks"])
            .current_dir(repo)
            .output()
            .context("failed to run git rev-parse")?;
        if !output.status.success() {
            bail!(
                "git rev-parse failed ({}): {}",
                output.status,
                String::from_utf8_lossy(&output.stderr).trim()
            );
        }
        let path = String::from_utf8(output.stdout).context("git printed a non-UTF-8 path")?;
        Ok(Self(PathBuf::from(path.trim())))
    }

    /// Each hook in `declared` that is not installed, and why.
    fn readiness(&self, declared: &DeclaredHooks) -> Vec<UninstalledHook> {
        declared
            .0
            .iter()
            .filter_map(|hook| {
                self.why_not_installed(hook).map(|because| UninstalledHook {
                    hook: hook.clone(),
                    because,
                })
            })
            .collect()
    }

    /// Why `hook` would not run prek's hooks, or `None` when it would.
    fn why_not_installed(&self, hook: &HookType) -> Option<NotInstalled> {
        use std::os::unix::fs::PermissionsExt;

        let path = self.0.join(&hook.0);
        let Ok(metadata) = std::fs::metadata(&path) else {
            return Some(NotInstalled::Missing);
        };
        if metadata.permissions().mode() & 0o111 == 0 {
            return Some(NotInstalled::NotExecutable);
        }
        // A hook that cannot be read cannot be shown to be prek's.
        let written_by_prek =
            std::fs::read_to_string(&path).is_ok_and(|contents| contents.contains(PREK_MARKER));
        (!written_by_prek).then_some(NotInstalled::NotPrek)
    }
}

/// Every declared hook not installed in the repository at `repo`, and the directory read.
///
/// # Errors
/// When `prek.toml` cannot be read or parsed, or git cannot say where the hooks live.
pub(crate) fn check(repo: &Path) -> Result<(HooksDir, Vec<UninstalledHook>)> {
    let path = repo.join("prek.toml");
    let text = std::fs::read_to_string(&path)
        .with_context(|| format!("failed to read {}", path.display()))?;
    let declared = DeclaredHooks::parse(&text)
        .with_context(|| format!("failed to read {}", path.display()))?;
    let dir = HooksDir::of(repo)?;
    let uninstalled = dir.readiness(&declared);
    Ok((dir, uninstalled))
}

/// Runs the check on the repository in the current directory, as `just check` does.
pub(crate) fn run() -> ExitCode {
    let outcome = std::env::current_dir()
        .context("failed to read the current directory")
        .and_then(|dir| check(&dir));
    match outcome {
        Ok((_, uninstalled)) if uninstalled.is_empty() => ExitCode::SUCCESS,
        Ok((dir, uninstalled)) => {
            eprintln!(
                "error: git hooks prek.toml declares are not installed in {}:",
                dir.0.display()
            );
            for hook in &uninstalled {
                let why = match hook.because {
                    NotInstalled::Missing => "missing",
                    NotInstalled::NotExecutable => "not executable",
                    NotInstalled::NotPrek => "not written by prek",
                };
                eprintln!("  {}: {why}", hook.hook);
            }
            eprintln!("  run `prek install` to install them");
            ExitCode::FAILURE
        }
        Err(error) => {
            eprintln!("error: could not check the git hooks prek.toml declares: {error:#}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use std::os::unix::fs::PermissionsExt;
    use std::process::Command;

    use rstest::rstest;
    use tempfile::TempDir;

    use super::*;

    /// Shaped like the hooks prek writes, but runs nothing, since the tests commit with it.
    const PREK_HOOK: &str =
        "#!/bin/sh\n# File generated by prek: https://github.com/j178/prek\nexit 0\n";

    fn hooks(names: &[&str]) -> DeclaredHooks {
        DeclaredHooks(names.iter().map(|n| HookType((*n).to_string())).collect())
    }

    fn write_hook(dir: &Path, name: &str, contents: &str, mode: u32) {
        std::fs::create_dir_all(dir).unwrap();
        let path = dir.join(name);
        std::fs::write(&path, contents).unwrap();
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(mode)).unwrap();
    }

    fn reasons(uninstalled: &[UninstalledHook]) -> Vec<(String, NotInstalled)> {
        uninstalled
            .iter()
            .map(|u| (u.hook.to_string(), u.because))
            .collect()
    }

    // ── what prek.toml declares ──────────────────────────────────────────────

    #[test]
    fn the_declared_hooks_are_default_install_hook_types() {
        let declared =
            DeclaredHooks::parse("default_install_hook_types = [\"pre-commit\", \"pre-push\"]\n")
                .unwrap();

        assert_eq!(declared, hooks(&["pre-commit", "pre-push"]));
    }

    #[test]
    fn without_the_key_only_pre_commit_is_declared() {
        let declared = DeclaredHooks::parse("[[repos]]\n  repo = \"local\"\n").unwrap();

        assert_eq!(declared, hooks(&["pre-commit"]));
    }

    #[rstest]
    #[case::not_toml("default_install_hook_types = [")]
    #[case::not_a_list("default_install_hook_types = \"pre-push\"")]
    #[case::not_strings("default_install_hook_types = [1]")]
    #[case::a_path("default_install_hook_types = [\"../pre-push\"]")]
    #[case::empty_name("default_install_hook_types = [\"\"]")]
    fn a_prek_toml_that_cannot_say_which_hooks_is_an_error(#[case] text: &str) {
        assert!(DeclaredHooks::parse(text).is_err(), "{text}");
    }

    // ── what is installed ────────────────────────────────────────────────────

    #[test]
    fn an_executable_hook_prek_wrote_is_installed() {
        let dir = tempfile::tempdir().unwrap();
        write_hook(dir.path(), "pre-push", PREK_HOOK, 0o755);

        let uninstalled = HooksDir(dir.path().to_path_buf()).readiness(&hooks(&["pre-push"]));

        assert_eq!(uninstalled, vec![]);
    }

    #[rstest]
    #[case::missing(None, NotInstalled::Missing)]
    #[case::not_executable(Some((PREK_HOOK, 0o644)), NotInstalled::NotExecutable)]
    #[case::someone_elses(Some(("#!/bin/sh\nexit 0\n", 0o755)), NotInstalled::NotPrek)]
    fn a_hook_that_would_not_run_prek_is_reported_with_why(
        #[case] file: Option<(&str, u32)>,
        #[case] because: NotInstalled,
    ) {
        let dir = tempfile::tempdir().unwrap();
        write_hook(dir.path(), "pre-commit", PREK_HOOK, 0o755);
        if let Some((contents, mode)) = file {
            write_hook(dir.path(), "pre-push", contents, mode);
        }

        let uninstalled =
            HooksDir(dir.path().to_path_buf()).readiness(&hooks(&["pre-commit", "pre-push"]));

        assert_eq!(
            reasons(&uninstalled),
            vec![("pre-push".to_string(), because)]
        );
    }

    // ── a real repository ────────────────────────────────────────────────────

    fn git(dir: &Path, args: &[&str]) {
        let status = Command::new("git")
            .args([
                "-c",
                "user.name=t",
                "-c",
                "user.email=t@t",
                "-c",
                "init.defaultBranch=main",
            ])
            .args(args)
            .current_dir(dir)
            .status()
            .unwrap();
        assert!(status.success(), "git {args:?} failed");
    }

    /// A repository declaring pre-commit and pre-push, with only pre-commit installed.
    fn repo_missing_pre_push() -> TempDir {
        let repo = tempfile::tempdir().unwrap();
        git(repo.path(), &["init", "-q"]);
        std::fs::write(
            repo.path().join("prek.toml"),
            "default_install_hook_types = [\"pre-commit\", \"pre-push\"]\n",
        )
        .unwrap();
        write_hook(
            &repo.path().join(".git/hooks"),
            "pre-commit",
            PREK_HOOK,
            0o755,
        );
        repo
    }

    #[test]
    fn a_clone_without_a_declared_hook_is_reported() {
        let repo = repo_missing_pre_push();

        let (_, uninstalled) = check(repo.path()).unwrap();

        assert_eq!(
            reasons(&uninstalled),
            vec![("pre-push".to_string(), NotInstalled::Missing)]
        );
    }

    #[test]
    fn a_worktree_reads_the_main_checkouts_hooks() {
        let repo = repo_missing_pre_push();
        write_hook(
            &repo.path().join(".git/hooks"),
            "pre-push",
            PREK_HOOK,
            0o755,
        );
        git(repo.path(), &["add", "prek.toml"]);
        git(repo.path(), &["commit", "-q", "-m", "init"]);
        let worktree = repo.path().join("wt");
        git(
            repo.path(),
            &["worktree", "add", "-q", worktree.to_str().unwrap()],
        );

        let (_, uninstalled) = check(&worktree).unwrap();

        assert_eq!(uninstalled, vec![]);
    }

    #[test]
    fn hooks_are_read_where_core_hooks_path_points() {
        let repo = repo_missing_pre_push();
        let elsewhere = repo.path().join("custom-hooks");
        write_hook(&elsewhere, "pre-commit", PREK_HOOK, 0o755);
        write_hook(&elsewhere, "pre-push", PREK_HOOK, 0o755);
        git(repo.path(), &["config", "core.hooksPath", "custom-hooks"]);

        let (dir, uninstalled) = check(repo.path()).unwrap();

        assert_eq!(uninstalled, vec![]);
        assert!(dir.0.ends_with("custom-hooks"), "{}", dir.0.display());
    }
}
